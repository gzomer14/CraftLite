/** As dezesseis cores, pelo `name` de `data/dyes.ts`. */
const DYE_COLORS_EN: Record<string, string> = {
  white: 'White', red: 'Red', orange: 'Orange', yellow: 'Yellow', green: 'Green', blue: 'Blue',
  purple: 'Purple', black: 'Black', light_gray: 'Light Gray', gray: 'Gray', brown: 'Brown',
  pink: 'Pink', lime: 'Lime', cyan: 'Cyan', light_blue: 'Light Blue', magenta: 'Magenta',
};

for (const [dye, color] of Object.entries(DYE_COLORS_EN)) {
  THING_NAMES_EN[`${dye}_wool`] = `${color} Wool`;
  THING_NAMES_EN[`${dye}_dye`] = `${color} Dye`;
  // A cama vermelha é a do M8 e ficou com o nome curto (`bed`).
  const bed = dye === 'red' ? 'bed' : `bed_${dye}`;
  THING_NAMES_EN[bed] = `${color} Bed`;
  THING_NAMES_EN[`${bed}_head`] = `${color} Bed`;
}

/** Ferramentas, armas e armaduras: material × peça, como `data/items.ts` monta. */
